BEGIN;

CREATE TABLE IF NOT EXISTS public.price_reports (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  reporter_user_id uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  reporter_username text NOT NULL,
  reporter_email text NOT NULL DEFAULT '',
  report_type text NOT NULL CHECK (report_type IN ('oferta', 'sobreprecio', 'actualizacion')),
  product_name text NOT NULL CHECK (char_length(product_name) BETWEEN 1 AND 160),
  store_name text NOT NULL CHECK (char_length(store_name) BETWEEN 1 AND 120),
  reported_price numeric(12, 2) NOT NULL CHECK (reported_price > 0),
  city text NOT NULL CHECK (char_length(city) BETWEEN 1 AND 100),
  comments text NOT NULL DEFAULT '' CHECK (char_length(comments) <= 1000),
  status text NOT NULL DEFAULT 'pendiente' CHECK (status IN ('pendiente', 'revisado', 'descartado')),
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS price_reports_created_at_idx
  ON public.price_reports(created_at DESC);

ALTER TABLE public.price_reports ENABLE ROW LEVEL SECURITY;

COMMIT;
